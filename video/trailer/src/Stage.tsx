export const Stage: React.FC<{t: number}> = ({t}) => {
  const pal = usePalette();
  const sprites = useSprites();
  const end = K(t, [[18.2, 0], [18.8, 1]]);
  const endGlow = K(t, [[18.4, 0], [19.0, 1]]);
  return (
    <div style={{position: 'absolute', inset: 0, overflow: 'hidden', background: pal.bg}}>
      <div style={{position: 'absolute', inset: 0, background: `radial-gradient(ellipse 90% 90% at 50% 55%, ${pal.stage[0]} 0%, ${pal.stage[1]} 50%, ${pal.stage[2]} 100%)`}} />
      {BLOOMS.map((b0, i) => {
        const b = pal.blooms && pal.blooms[i] ? {...b0, c: pal.blooms[i][0], core: pal.blooms[i][1]} : b0;
        const [x, y, w0, h0, o] = KV(t, b.keys, (v) => v);
        const w = w0 * 1.3;
        const h = h0 * 1.3;
        if (o <= 0.01) return null;
        const px = (x / 100) * 1920;
        const py = (y / 100) * 1080;
        if (sprites)
          return <img key={i} src={staticFile(`sprites/bloom_${i}.png`)} style={{position: 'absolute', left: px - w / 2, top: py - h / 2, width: w, height: h, opacity: o}} />;
        return (
          <div
            key={i}
            style={{
              position: 'absolute',
              left: px - w / 2,
              top: py - h / 2,
              width: w,
              height: h,
              opacity: o,
              background: `radial-gradient(closest-side, ${rgba(hex(b.core), 0.98)} 0%, ${rgba(hex(b.c), 0.95)} 14%, ${rgba(hex(b.c), 0.5)} 42%, ${rgba(hex(b.c), 0.14)} 72%, ${rgba(hex(b.c), 0)} 100%)`,
            }}
          />
        );
      })}
      <div style={{position: 'absolute', inset: 0, background: `rgba(24,10,52,${0.28 * end})`}} />
      <div style={{position: 'absolute', left: 300, top: 150, width: 1000, height: 800, opacity: 0.5 * endGlow, background: 'radial-gradient(closest-side, rgba(110,60,230,0.55), rgba(110,60,230,0))'}} />
      <div style={{position: 'absolute', inset: 0, background: 'radial-gradient(ellipse 80% 80% at 50% 50%, rgba(0,0,0,0) 55%, rgba(5,2,25,0.3) 100%)'}} />
    </div>
  );
};
